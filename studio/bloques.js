export const BLOCK_SHAPES = Object.fromEntries(Object.entries(SHAPE_IDS).flatMap(([shape, ids]) => ids.map((id) => [id, shape])));
// Full cubes you see through (glass and the like) and blocks the game never draws.
export const SEE_THROUGH = new Set([27, 56, 84, 110, 137]);
export const HIDDEN = new Set([215]);

// Cuadros del atlas con partes transparentes (hojas, plantas, vidrio, escaleras, rejas).
// El atlas del juego no trae transparencia real: todo tiene la misma opacidad y
// lo transparente es negro puro. Estos cuadros se recortan donde son negros.
export const TILES_RECORTE = new Set(
  Object.entries(BLOCK_TILES).flatMap(([id, t]) => (SEE_THROUGH.has(+id) || (BLOCK_SHAPES[id] && !BLOCK_SHAPES[id].startsWith("slab")) ? t : [])),
);

export const blockTile = (id, up) => {
  const tiles = BLOCK_TILES[id];
  if (!tiles) return null;
  const face = up > 0 ? 2 : up < 0 ? 1 : 0;
  return tiles[Math.min(face, tiles.length - 1)];
};
